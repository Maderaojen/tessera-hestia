import type { Turn } from '../types.js';

// followUp: a user message the CLI took in while a reply was still being
// written (see Turn.followUps) — it joins the turn in progress rather than
// starting a new one.
// interrupted: the CLI's note that the user stopped the reply here (an
// assistant Msg with no text of its own). It closes the turn as finished
// and marked interrupted — keeping the user's own message even when nothing
// was generated yet, since assembleCompleteTurns otherwise drops a user
// message with no reply after it.
export type Msg = { role: 'user' | 'assistant'; text: string; ts: string | null; followUp?: boolean; interrupted?: true };

// Synthetic/wrapper user messages the CLIs inject (slash-command echoes,
// hook output, environment context, ...) — never real conversation.
// Ported from tessera-mnemosyne's WRAPPER_PREFIXES so a reply the user
// never actually typed can't be mistaken for their turn.
const WRAPPER_PREFIXES = [
  '<session_context>',
  '<environment_context>',
  '<model_switch>',
  '<command-message>',
  '<command-name>',
  '<command-args>',
  '<local-command-stdout>',
  '<local-command-caveat>',
  '<user-prompt-submit-hook>',
  '<user-memory-input>',
  '<task-notification>',
  'Caveat: The messages below were generated by the user while running local commands',
];

export function isWrapper(text: string): boolean {
  const head = text.trimStart();
  return WRAPPER_PREFIXES.some((p) => head.startsWith(p));
}

const PROSE_TYPES = new Set([
  'text',
  'input_text',
  'output_text',
  'message',
  'user_message',
  'assistant_message',
]);
const TOOL_TYPES = new Set([
  'tool_use',
  'tool_result',
  'function_call',
  'function_call_output',
  'thinking',
  'reasoning',
]);

// Ported from tessera-mnemosyne's text_from_content: keeps only human/model
// prose from a content block, skipping tool_use/tool_result/thinking so a
// reply never includes tool call payloads or hidden reasoning.
export function textFromContent(value: unknown): string {
  if (typeof value === 'string') return value.trim();

  if (Array.isArray(value)) {
    const parts: string[] = [];
    for (const item of value) {
      if (typeof item === 'string') {
        parts.push(item);
        continue;
      }
      if (item && typeof item === 'object') {
        const obj = item as Record<string, unknown>;
        const typ = typeof obj.type === 'string' ? obj.type : '';
        const looksLikeProse = PROSE_TYPES.has(typ) || (typ === '' && 'text' in obj && !TOOL_TYPES.has(typ));
        if (looksLikeProse) {
          const txt = obj.text ?? obj.content ?? obj.value;
          if (typeof txt === 'string') parts.push(txt);
        }
      }
    }
    return parts
      .map((p) => p.trim())
      .filter(Boolean)
      .join('\n')
      .trim();
  }

  if (value && typeof value === 'object') {
    const obj = value as Record<string, unknown>;
    for (const key of ['text', 'content', 'message']) {
      if (key in obj) {
        const txt = textFromContent(obj[key]);
        if (txt) return txt;
      }
    }
  }

  return '';
}

export function dedupe<T extends Msg>(messages: T[]): T[] {
  const result: T[] = [];
  for (const m of messages) {
    const last = result[result.length - 1];
    if (last && last.role === m.role && last.text === m.text && last.interrupted === m.interrupted) continue;
    result.push(m);
  }
  return result;
}

// A message together with where it came from in the CLI's transcript (its
// record's position), so a turn can be traced back to the records it was
// built from (process/: the tools and thinking around its text).
export type SourcedMsg = Msg & { src: number };
export type SourcedTurn = { turn: Turn; userSrc: number; assistantSrcs: number[] };

// Collapses a flat message list into complete user -> assistant turns.
// A trailing user message with no assistant reply yet is dropped — it's
// the in-progress turn, not something to hand back to the frontend.
export function assembleCompleteTurns(messages: Msg[]): Turn[] {
  return assembleSourcedTurns(messages.map((message, src) => ({ ...message, src }))).map((sourced) => sourced.turn);
}

// assembleCompleteTurns, keeping which messages each turn was made of.
export function assembleSourcedTurns(messages: SourcedMsg[]): SourcedTurn[] {
  const turns: SourcedTurn[] = [];
  let curUser: SourcedMsg | null = null;
  let followUps: { text: string; at: string | null }[] = [];
  let parts: string[] = [];
  let assistantSrcs: number[] = [];
  let interrupted = false;
  let assistantTs: string | null = null;

  const flush = () => {
    if (curUser && (parts.length > 0 || interrupted)) {
      turns.push({
        turn: {
          index: turns.length + 1,
          user: { text: curUser.text, at: curUser.ts },
          ...(followUps.length > 0 ? { followUps } : {}),
          assistant: { text: parts.join('\n\n'), at: assistantTs, ...(interrupted ? { interrupted: true as const } : {}) },
        },
        userSrc: curUser.src,
        assistantSrcs,
      });
    }
    followUps = [];
    parts = [];
    assistantSrcs = [];
    interrupted = false;
    assistantTs = null;
  };

  for (const m of messages) {
    if (m.role === 'user' && m.followUp && curUser) {
      followUps.push({ text: m.text, at: m.ts });
    } else if (m.role === 'user') {
      flush();
      curUser = m;
    } else if (m.role === 'assistant' && curUser) {
      if (m.interrupted) interrupted = true;
      else {
        parts.push(m.text);
        assistantSrcs.push(m.src);
      }
      assistantTs ??= m.ts;
    }
  }
  flush();
  return turns;
}
